//! 로컬 상태 — **캐시 성격**의 서버 측 기록.
//!
//! ## 이 계층의 아이러니를 먼저 밝힌다
//! x-backup은 지금까지 **로컬 상태가 없었다.** 무슨 백업이 있는지에 대한 진실의 원천은
//! 언제나 destination의 manifest였고([`crate::manifest::store`]), CLI는 그것만 읽고 쓰면
//! 됐다. 그래서 백업 도구 자신은 백업할 것이 없었다 — 서버를 새로 세워도 destination만
//! 붙이면 카탈로그가 그대로 살아난다.
//!
//! 웹 콘솔은 그 성질을 깬다. "누가 언제 어떤 버튼을 눌렀고 그 잡의 로그가 무엇이었나"는
//! manifest에 없다. 그 기록을 남기는 순간 **백업 도구에 처음으로 "백업해야 할 상태"가
//! 생긴다.** 이 계층은 그 상태를 다루면서도 그 대가를 최소화하기 위한 규칙 하나를 지킨다:
//!
//! > **여기 있는 모든 것은 manifest에서 재구성 가능한 캐시다.** 상태 파일이 통째로
//! > 날아가도 백업 자체는 멀쩡하고, `x-backup list --json`으로 "무슨 백업이 있는지"는
//! > 언제든 복원된다. 잃는 것은 "누가 언제 눌렀는지"뿐이다.
//!
//! 이 규칙이 코드에 어떻게 나타나는가:
//!
//! 1. **상태 파일이 없거나 깨져도 서버는 뜬다.** [`jobs::JobStore::open`]은 실패를
//!    반환하지 않고 경고만 남긴다. 감사 로그([`crate::web::audit`])가 fail-closed인 것과
//!    정반대인데, 근거도 정반대다 — 감사 로그를 못 쓰면 파괴적 작업이 **어차피 전부
//!    거부되므로** 그 사실을 기동 시점에 알려야 한다. 잡 이력을 못 쓰면 잃는 것은 화면
//!    한 장이고, 그것 때문에 콘솔 전체를 못 띄우면 운영자는 장애 대응 중에 터미널로
//!    돌아가야 한다. 그게 더 나쁘다.
//! 2. **읽기 경로는 상태를 만들지 않는다.** 화면(GET)은 [`jobs::JobStore::attach`]로
//!    붙어 디렉터리를 만들지 않는다. "이력 화면을 열었더니 파일이 생겼다"는 일이 없다.
//! 3. **손상은 삼키지 않고 센다.** 읽을 수 없는 줄은 건너뛰되 개수를 세어
//!    ([`jobs::JobHistory::unreadable_lines`]) 화면이 "일부를 못 읽었다"고 말할 수 있게
//!    한다. 조용히 사라진 이력은 사라진 줄도 모른다.
//!
//! ## 왜 SQLite가 아닌가
//! `rusqlite`의 `bundled` feature는 C 컴파일러를 요구한다. x-backup은 musl 정적 링크로
//! 4개 플랫폼 바이너리를 내는 것이 릴리스 전제이므로(README), 크로스 컴파일 경로에 C
//! 툴체인 변수를 들이는 대가가 트랜잭션·인덱스로 얻는 이득보다 크다. 우리가 필요한 질의는
//! "최근 N건" 하나뿐이고, 그건 append-only NDJSON + 파일명 정렬로 충분하다.
//!
//! ## 모듈 구성
//! - [`jobs`]: 잡 이력(요약 인덱스 + 잡별 이벤트 로그).

